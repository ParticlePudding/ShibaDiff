def rep(L, old, new, at=None):
    """段落のリスト L の中で、old を含む段落（at があれば、at も含む段落）を1つだけ見つけて new に置き換える。段落の番号を返す"""
    hit = [i for i, x in enumerate(L) if isinstance(x, str) and old in x and (at is None or at in x)]
    assert len(hit) == 1 and L[hit[0]].count(old) == 1, (old, at, hit)
    L[hit[0]] = L[hit[0]].replace(old, new); return hit[0]


def cell(rows, r, c, old, new):
    """表 rows の r 行 c 列が old であることを確かめて new にする"""
    assert rows[r][c] == old, (r, c, rows[r][c], old)
    rows[r][c] = new


def data_uri(im, fmt='JPEG', **kw):
    b = io.BytesIO(); im.save(b, fmt, **kw)
    return f'data:image/{fmt.lower()};base64,' + base64.b64encode(b.getvalue()).decode()


def chrome_now(jobs):
    """ブラウザの印刷をその場で行う（ページ数を先に知りたいとき・POST の中で使う）。jobs = [(出力先の絶対パス, html, opts)]"""
    async def mk():
        from playwright.async_api import async_playwright
        async with async_playwright() as p:
            b = await p.chromium.launch(executable_path=G.chrome_path(), args=['--no-sandbox']); pg = await b.new_page()
            for path, html, o in jobs:
                await pg.set_content(html); await pg.wait_for_timeout(150)
                await pg.pdf(path=path, format=o.get('format', 'A4'), landscape=o.get('landscape', False), margin=o.get('margin'), print_background=True,
                             display_header_footer=o.get('display_header_footer', False), header_template=o.get('header_template', '<span></span>'), footer_template=o.get('footer_template', '<span></span>'),
                             prefer_css_page_size=o.get('prefer_css_page_size', False))
            await b.close()
    asyncio.run(mk())


def pdf_pages(path):
    """PDF の各ページの文字（pdftotext）。空白と改行は取り除く"""
    out = subprocess.run(['pdftotext', '-enc', 'UTF-8', path, '-'], capture_output=True, check=True).stdout.decode('utf-8')
    pages = out.split('\f')
    if pages and not pages[-1].strip(): pages.pop()
    return [re.sub(r'\s+', '', p) for p in pages]


def noise_rgb(a, rnd, amp):
    """numpy の画像 a（H×W×3、float）に、写真のざらつきを足す"""
    return a + rnd.normal(0, amp, a.shape[:2])[..., None]


def to_img(a): return Image.fromarray(np.clip(a, 0, 255).astype('uint8'), 'RGB')


def vgrad(W, H, top, bot):
    t = np.linspace(0, 1, H)[:, None, None]
    return np.broadcast_to(np.array(top, float) * (1 - t) + np.array(bot, float) * t, (H, W, 3)).copy()


