def deck(path, slides, doc):
    """決算説明の PowerPoint。slides の要素：{'cover', 'title', 'sub', 'bullets', 'table', 'boxes', 'notes'}。右下にスライド番号を入れる"""
    pr = Presentation(); pr.slide_width = Inches(13.333); pr.slide_height = Inches(7.5)
    for i, s in enumerate(slides):
        if s.get('cover'):
            sl = pr.slides.add_slide(pr.slide_layouts[0]); t = sl.shapes.title; t.left, t.top, t.width, t.height = Inches(1), Inches(2.1), Inches(11.3), Inches(1.5); t.text = s['title']
            st = sl.placeholders[1]; st.left, st.top, st.width, st.height = Inches(1), Inches(3.9), Inches(11.3), Inches(1.6); st.text = s['sub']
        else:
            sl = pr.slides.add_slide(pr.slide_layouts[5]); t = sl.shapes.title; t.left, t.top, t.width, t.height = Inches(0.6), Inches(0.3), Inches(12.1), Inches(0.95); t.text = s['title']
            t.text_frame.paragraphs[0].font.size = PPt(30); y = 1.5
            if s.get('bullets'):
                tb = sl.shapes.add_textbox(Inches(0.7), Inches(y), Inches(6.2 if s.get('boxes') else 12.0), Inches(0.55 * len(s['bullets']))); tf = tb.text_frame; tf.word_wrap = True
                for k, b in enumerate(s['bullets']):
                    p = tf.paragraphs[0] if k == 0 else tf.add_paragraph(); p.text = '・' + b; p.font.size = PPt(18); p.space_after = PPt(8)
                if not s.get('boxes'): y += 0.6 * len(s['bullets']) + 0.25
            if s.get('table'):
                rows = s['table']; gt = sl.shapes.add_table(len(rows), len(rows[0]), Inches(0.7), Inches(y), Inches(12.0), Inches(0.44 * len(rows))).table
                for r, row in enumerate(rows):
                    for c, v in enumerate(row):
                        gt.cell(r, c).text = str(v); gt.cell(r, c).text_frame.paragraphs[0].font.size = PPt(14)
            for x, yy, w, h, txt, col in s.get('boxes', []):
                sh = sl.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(yy), Inches(w), Inches(h)); sh.fill.solid(); sh.fill.fore_color.rgb = RGBColor(*col); sh.line.fill.background()
                sh.text_frame.word_wrap = True; sh.text_frame.text = txt
                for p in sh.text_frame.paragraphs: p.font.size = PPt(16); p.font.bold = True
        fb = sl.shapes.add_textbox(Inches(0.5), Inches(6.98), Inches(9), Inches(0.35)); fb.text_frame.text = doc; fb.text_frame.paragraphs[0].font.size = PPt(10)
        nb = sl.shapes.add_textbox(Inches(12.2), Inches(6.98), Inches(0.8), Inches(0.35)); nb.text_frame.text = str(i + 1); nb.text_frame.paragraphs[0].font.size = PPt(10)
        if s.get('notes'): sl.notes_slide.notes_text_frame.text = s['notes']
    pr.save(P(path))


